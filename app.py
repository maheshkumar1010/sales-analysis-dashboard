# ==========================================
# SALES FORECASTING USING MACHINE LEARNING
# ==========================================

st.divider()

st.header("🔮 Sales Forecasting using Machine Learning")


# Calculate Monthly Sales

monthly_data = (
    data.set_index("Date")["Sales"]
    .resample("ME")
    .sum()
)


if len(monthly_data) >= 4:

    # Prepare Data for Machine Learning

    X = pd.DataFrame({
        "Month_Number": range(len(monthly_data))
    })

    y = monthly_data.values


    # Split Data into Training and Testing

    split_index = int(len(X) * 0.8)

    X_train = X.iloc[:split_index]

    X_test = X.iloc[split_index:]

    y_train = y[:split_index]

    y_test = y[split_index:]


    # Train Model

    model = LinearRegression()

    model.fit(X_train, y_train)


    # Test Model Performance

    predicted_values = model.predict(X_test)

    mae = mean_absolute_error(
        y_test,
        predicted_values
    )


    # Display Model Performance

    st.subheader("🤖 Machine Learning Model Performance")

    col1, col2 = st.columns(2)

    with col1:

        st.metric(
            "Mean Absolute Error (MAE)",
            f"₹{mae:,.2f}"
        )

    with col2:

        if len(y_test) >= 2:

            r2 = r2_score(
                y_test,
                predicted_values
            )

            st.metric(
                "R² Score",
                f"{r2:.2f}"
            )

        else:

            st.metric(
                "R² Score",
                "Not enough test data"
            )


    # Train Final Model Using All Data

    model.fit(X, y)


    # Predict Next Month Sales

    future_month = pd.DataFrame({
        "Month_Number": [len(monthly_data)]
    })

    predicted_sales = max(
    0,
    model.predict(future_month)[0]
)


    # Display Prediction

    st.success(
        f"Predicted Sales for Next Month: "
        f"₹{predicted_sales:,.2f}"
    )


    # Prepare Forecasting Graph

    next_month = (
        monthly_data.index[-1] +
        pd.offsets.MonthEnd(1)
    )

    chart_data = pd.DataFrame(
        index=monthly_data.index.append(
            pd.DatetimeIndex([next_month])
        )
    )

    chart_data["Actual Sales"] = (
        monthly_data.reindex(chart_data.index)
    )

    chart_data["Predicted Sales"] = float("nan")

    chart_data.loc[
        monthly_data.index[-1],
        "Predicted Sales"
    ] = monthly_data.iloc[-1]

    chart_data.loc[
        next_month,
        "Predicted Sales"
    ] = predicted_sales


    # Display Forecasting Graph

    st.subheader(
        "📈 Actual Sales vs Predicted Sales"
    )

    chart_data.index = (
        chart_data.index.strftime("%B %Y")
    )

    st.line_chart(chart_data)


    st.warning(
        "This is a demonstration prediction. "
        "More historical monthly data is needed "
        "for reliable forecasting."
    )

    st.caption(
        "MAE and R² are calculated using separate test data. "
        "The final forecasting model is trained using all available data."
    )


else:

    st.warning(
        "At least four months of sales data are required "
        "for this model evaluation."
    )


